import { BodyTrend } from "./components/BodyTrend";
import { Consistency } from "./components/Consistency";
import { Kpis } from "./components/Kpis";
import { MuscleVolume } from "./components/MuscleVolume";
import { PrTable } from "./components/PrTable";
import { StrengthTrend } from "./components/StrengthTrend";
import { UploadPanel } from "./components/UploadPanel";
import { fmtDate } from "./format";
import { META } from "./queries";
import { useDatasetSource, useDatasetVersion, useQuery } from "./useQuery";

const REPO = "https://github.com/Sam-Razavi/liftpipe";

export function App() {
  const meta = useQuery<{ first_day: string; last_day: string }>(META);
  const range = meta.status === "ready" ? meta.rows[0] : null;
  const source = useDatasetSource();
  const version = useDatasetVersion();

  return (
    <main className="page">
      <header className="header">
        <div>
          <h1>liftpipe</h1>
          <p>
            Strength and body-composition analytics from Hevy and Apple Health exports, modelled with dbt on DuckDB and
            orchestrated by Dagster. This page queries the mart Parquet files in your browser with DuckDB-WASM.
          </p>
        </div>
        <span
          className="badge"
          title={
            source === "demo"
              ? "Generated by the project's synthetic data generator; no personal data"
              : "Built from your upload and held only in this browser tab"
          }
        >
          {source === "demo" ? "Synthetic demo data" : "Your data"}
          {range && ` · ${fmtDate(range.first_day)} – ${fmtDate(range.last_day)}`}
        </span>
      </header>

      {meta.status === "error" && (
        <div className="banner" role="alert">
          The analytics engine could not start in this browser ({meta.error}). DuckDB-WASM needs a
          recent version of Chrome, Edge, Firefox or Safari.
        </div>
      )}

      <UploadPanel />

      <Kpis key={`kpis-${version}`} />

      <div className="grid" key={`grid-${version}`}>
        <StrengthTrend />
        <PrTable />
        <MuscleVolume />
        <BodyTrend />
        <Consistency />
      </div>

      <footer className="footer">
        Pipeline: Polars and lxml ingestion → Parquet → DuckDB → dbt (staging, intermediate, marts, tests) →
        Parquet → DuckDB-WASM. Source and architecture on <a href={REPO}>GitHub</a>.
      </footer>
    </main>
  );
}
